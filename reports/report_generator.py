"""
reports/report_generator.py

Phase 5: turns an investigated InvestigationCase into a standalone incident
report -- the artifact an analyst actually forwards or files, as opposed
to the CLI output made for reading in a terminal.

Two formats:
  - markdown (stdlib only, always available)
  - html (needs Jinja2 -- see requirements.txt)

Both are pure presentation over the same InvestigationCase tree Phase 1-3
already built; this module makes zero investigation decisions of its own,
same discipline as the orchestrator.
"""

import os
from datetime import datetime, timezone

from core.models import InvestigationCase


def _severity_badge(severity: str) -> str:
    colors = {"low": "#2e7d32", "medium": "#f9a825", "high": "#e65100", "critical": "#c62828"}
    return colors.get(severity, "#616161")


def to_markdown(case: InvestigationCase) -> str:
    lines = []
    lines.append(f"# PhishMind Incident Report -- {case.case_id}")
    lines.append("")
    lines.append(f"**Source file:** `{case.source_file}`  ")
    lines.append(f"**Analyzed at:** {case.analyzed_at}  ")
    lines.append(f"**Subject:** {case.subject or '(none)'}  ")
    lines.append("")

    ta = case.threat_assessment
    if ta:
        lines.append(f"## Verdict: {ta.verdict.upper()}")
        lines.append(f"- **Severity:** {ta.severity}")
        lines.append(f"- **Confidence:** {ta.confidence}")
        lines.append(f"- **Analyst review recommended:** {ta.analyst_review_recommended}")
        if ta.possible_attack_objective:
            lines.append(f"- **Possible objective:** {ta.possible_attack_objective}")
        lines.append("")
        lines.append("### Reasons")
        for r in ta.reasons:
            lines.append(f"- {r}")
        if ta.mitre_techniques:
            lines.append("")
            lines.append("### MITRE ATT&CK")
            for t in ta.mitre_techniques:
                lines.append(f"- `{t.technique_id}` -- {t.technique_name} (justified by: {', '.join(t.justified_by) or 'n/a'})")
        if ta.missing_evidence:
            lines.append("")
            lines.append("### Missing evidence / limitations")
            for m in ta.missing_evidence:
                lines.append(f"- {m}")

    ra = case.recommended_action
    if ra:
        lines.append("")
        lines.append("### Recommended action")
        lines.append(f"- **Action:** {ra.action} (requires human approval: {ra.requires_human_approval})")
        lines.append(f"- **Rationale:** {ra.rationale}")

    lines.append("")
    lines.append("## Sender analysis")
    s = case.sender
    lines.append(f"- From: {s.from_display_name} <{s.from_address}>")
    lines.append(f"- Reply-To mismatch: {s.reply_to_mismatch}")
    lines.append(f"- Return-Path mismatch: {s.return_path_mismatch}")
    lines.append(f"- Display-name spoof suspected: {s.display_name_spoof_suspected}")

    a = case.authentication
    lines.append("")
    lines.append("## Authentication (as reported by receiving server)")
    if a.header_present:
        lines.append(f"- SPF: {a.spf} | DKIM: {a.dkim} | DMARC: {a.dmarc}")
    else:
        lines.append("- No Authentication-Results header present.")

    e = case.evidence
    lines.append("")
    lines.append("## Evidence")
    lines.append(f"- URLs ({len(e.urls)}): " + (", ".join(e.urls) if e.urls else "none"))
    lines.append(f"- Domains ({len(e.domains)}): " + (", ".join(e.domains) if e.domains else "none"))
    lines.append(f"- Public IPs ({len(e.ip_addresses)}): " + (", ".join(e.ip_addresses) if e.ip_addresses else "none"))
    lines.append(f"- Attachments ({len(e.attachments)}): " + (", ".join(f"{att.filename} ({att.sha256[:12]}...)" for att in e.attachments) if e.attachments else "none"))

    if case.agent_findings:
        lines.append("")
        lines.append("## Agent findings")
        for f in case.agent_findings:
            lines.append(f"### {f.agent_name} (confidence={f.confidence}, severity={f.severity})")
            lines.append(f"{f.finding}")
            lines.append("")

    if case.enrichment_results:
        lines.append("## Threat-intel enrichment")
        for r in case.enrichment_results:
            if r.available:
                lines.append(f"- {r.source} / {r.indicator}: malicious_votes={r.malicious_votes}, reputation_score={r.reputation_score}")
            else:
                lines.append(f"- {r.source} / {r.indicator}: unavailable ({r.reason})")

    lines.append("")
    lines.append(f"*Generated by PhishMind on {datetime.now(timezone.utc).isoformat()}. "
                  f"All recommended actions require human analyst approval before execution.*")

    return "\n".join(lines)


