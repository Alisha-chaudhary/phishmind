def to_html(case: InvestigationCase) -> str:
    try:
        from jinja2 import Template
    except ImportError as exc:
        raise RuntimeError(
            "HTML report generation requires jinja2 (pip install jinja2 --break-system-packages). "
            "Use --report md for a dependency-free alternative."
        ) from exc

    template = Template(HTML_TEMPLATE)
    ta = case.threat_assessment
    badge_color = _severity_badge(ta.severity) if ta else "#616161"
    return template.render(case=case, ta=ta, ra=case.recommended_action, badge_color=badge_color)


def write_report(case: InvestigationCase, fmt: str, out_dir: str = "reports") -> str:
    os.makedirs(out_dir, exist_ok=True)
    ext = "html" if fmt == "html" else "md"
    path = os.path.join(out_dir, f"{case.case_id}.{ext}")
    content = to_html(case) if fmt == "html" else to_markdown(case)
    with open(path, "w") as f:
        f.write(content)
    return path

